//! The book's chapters, compiled as doctests: `cargo test -p vantage-docs --doc`.

macro_rules! chapters {
    ($($name:ident => $path:literal,)*) => {
        #[cfg(doctest)]
        mod compiled {
            $(
                #[doc = include_str!($path)]
                pub struct $name;
            )*
        }

        #[cfg(test)]
        pub(crate) const CHAPTERS: &[&str] = &[$($path),*];
    };
}

